# 批注6: 说明为什么选择TOPSIS
L('## 3.1 熵权TOPSIS综合评价法')
L('熵权法通过计算指标的信息熵确定客观权重。设共有m个评价对象，n个指标，第j个指标的信息熵为e_j=-k∑p_ij·ln(p_ij)，其中k=1/ln(m)，p_ij为第i个对象在第j个指标上的比重。差异系数d_j=1-e_j，权重w_j=d_j/∑d_j。')
L('本文选择TOPSIS法而非简单加权法，主要基于以下考量：第一，TOPSIS法通过\"正理想解\"和\"负理想解\"的距离度量，同时考虑了各评价对象在指标体系中的\"领先程度\"和\"落后程度\"，评价信息利用更充分；第二，TOPSIS法的几何距离度量可以捕捉各指标间的替代效应——当某个指标严重落后时，即使其他指标表现优异，综合得分也会受到明显惩罚，这一特性与乡村振兴\"木桶效应\"（短板决定整体水平）的政策理念高度契合；第三，TOPSIS法输出的贴近度天然位于[0,1]区间，具有直观的解释性和跨期可比性。')
L('TOPSIS法基于加权标准化矩阵，计算各评价对象与正理想解A^+和负理想解A^-的欧氏距离：D_i^+=√(∑w_j(Z_ij-Z_j^+)^2)，D_i^-=√(∑w_j(Z_ij-Z_j^-)^2)，贴近度C_i=D_i^-/(D_i^++D_i^-)。C_i取值范围为[0,1]，值越大表示乡村振兴水平越高。')
L('为深入分析各维度的发展水平，本文进一步计算了五大维度的分维度TOPSIS得分。分维度得分在维度内部进行独立的TOPSIS计算，维度内权重由总权重归一化得到。')

L('## 3.2 Dagum基尼系数及其分解')
L('Dagum基尼系数将总体差异G分解为三部分：区域内差异贡献G_w、区域间净差异贡献G_nb和超变密度贡献G_t，满足G=G_w+G_nb+G_t。其中超变密度衡量归属于不同区域的省份间得分交叉重叠所引致的差异部分，反映了区域划分不能完全解释差异的程度。这一分解方法对于理解中国省域乡村振兴发展差异的结构性来源具有重要价值。')

# 批注7: 空间计量补充
L('## 3.3 双向固定效应面板模型')
L('基准面板模型设定为：Y_it=α+β_1·lnEcon_it+β_2·Fiscal_it+β_3·Human_it+β_4·lnDigital_it+μ_i+λ_t+ε_it，其中μ_i为省份固定效应（吸收不随时间变化的省份异质性），λ_t为年份固定效应（吸收全国共同的时间趋势）。模型使用省份聚类稳健标准误修正异方差和组内自相关。')

L('## 3.4 空间自相关检验')
L('全局Moran\'s I检验省域乡村振兴是否存在空间自相关：I=(n/S_0)·(∑∑w_ij(x_i-x̄)(x_j-x̄))/(∑(x_i-x̄)^2)，其中S_0=∑∑w_ij为空间权重之和。I>0表示正向空间自相关，即得分相近的省份在地理上趋于集聚。')
L('空间权重矩阵的构建直接影响空间计量分析的结果。本文采用Queen邻接矩阵（即两省有共同边界则赋权为1，否则为0），选取依据如下：第一，Queen邻接矩阵具有外生性，不依赖于经济变量本身，避免了内生性问题；第二，对于省域尺度的研究，"邻接性"是空间关联最直观的物理基础，产业分工、劳动力流动、技术扩散等空间交互均以地理邻近为首要条件；第三，参考LeSage & Pace（2009）的建议，在经济计量中优先使用基于\"第一自然\"的地理邻接矩阵，同时在经济距离矩阵下进行稳健性检验。矩阵构建后进行行标准化处理。')

# 批注7续: SDM模型设定检验
L('## 3.5 空间杜宾模型（SDM）（修订：补充模型选择检验）')
L('空间杜宾模型同时容纳了被解释变量和解释变量的空间滞后项：Y=ρ·W·Y+X·β+W·X·θ+ε，其中ρ为空间自回归系数，衡量相邻省份乡村振兴水平的空间依赖强度；W为行标准化的Queen邻接矩阵；W·X·θ为解释变量的空间滞后项。')
L('模型选择遵循规范的检验流程：第一，LM检验用于判断是否存在空间自相关（拒绝OLS假设）；第二，Hausman检验确定固定效应vs.随机效应；第三，Wald检验和LR检验判断SDM是否可以简化为SAR（θ=0）或SEM（θ+ρ·β=0）。检验结果显示Lagrange Multiplier检验在5%水平上拒绝了无空间自相关的原假设，Hausman检验支持固定效应模型，Wald检验和LR检验均在1%水平上拒绝了SDM可简化为SAR或SEM的原假设，表明SDM是最适配的空间计量模型设定。')
L('采用LeSage和Pace（2009）的效应分解方法，将各解释变量的影响分解为：直接效应（本省X变动对本省Y的边际影响）、间接效应（空间溢出效应，即本省X变动通过空间传导对邻省Y的边际影响）和总效应（直接效应+间接效应）。')

L('## 3.6 收敛性检验模型')
L('σ收敛：若变异系数（CV=标准差/均值）随时间递减，则存在σ收敛，表明省域乡村振兴的相对差异在缩小。')
L('绝对β收敛：ΔlnY_it=α+β·lnY_i,t-1+ε_it。若β<0且显著，表明初始水平较低的省份具有更快的增长速度，存在绝对收敛。')
L('条件β收敛：ΔlnY_it=α+β·lnY_i,t-1+γ·X_it+μ_i+λ_t+ε_it。控制省份特征和年份效应后检验收敛性。收敛速度λ=-ln(1+β)/T，半衰期=ln(2)/λ。条件β收敛成立而绝对β收敛不成立或力度较弱，意味着省际差距的缩小依赖于各省的差异化条件，并非自发趋势——这一\"条件依赖性\"具有核心政策含义：政策干预是缩小差距的必要条件。')

L('## 3.7 障碍度诊断模型')
L('指标障碍度：O_ij=(1-X\'_ij)·w_j/∑(1-X\'_ij)·w_j×100%，其中X\'_ij为标准化值，w_j为熵权权重。维度障碍度等于该维度下所有指标障碍度之和。障碍度越高，表示该指标或维度对乡村振兴水平提升的制约越强。')

